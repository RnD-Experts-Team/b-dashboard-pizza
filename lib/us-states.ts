/** "Ohio", "ohio ", "oh" -> "OH"; null if it isn't a state. For loading old free-text rows. */
export function toStateCode(value: string | null | undefined): string | null {
  const key = (value ?? "").replace(/\./g, "").replace(/\s+/g, " ").trim().toUpperCase();
  if (key === "") return null;

  const match = US_STATES.find((s) => s.code === key || s.name.toUpperCase() === key);
  return match?.code ?? null;
}
